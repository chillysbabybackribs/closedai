// Builds the first-turn session guide injected as closedai.guide. Edit agent-guide-outline.json,
// not the generated TypeScript. Run with --write to refresh, --check for the completion gate.
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outlinePath = path.join(root, 'scripts/agent-guide-outline.json')
const outputPath = path.join(root, 'src/main/chat-context/agent-guide.generated.ts')

function renderGuide(outline) {
  const parts = [`ClosedAI session guide (generated ${outline.generatedDate ?? 'from outline'}).`, '']
  for (const section of outline.sections) {
    parts.push(`## ${section.heading}`, ...section.lines, '')
  }
  let text = parts.join('\n').trimEnd()
  const maxChars = outline.maxChars ?? 8000
  if (text.length > maxChars) {
    throw new Error(`Agent guide exceeds ${maxChars} characters (${text.length})`)
  }
  return text
}

function emitModule(text, outlineHash) {
  return `// Generated by scripts/agent-guide-generate.mjs — do not edit by hand.
// Outline hash: ${outlineHash}

export const AGENT_GUIDE_OUTLINE_SHA256 = ${JSON.stringify(outlineHash)}

export const AGENT_GUIDE_TEXT = ${JSON.stringify(text)}
`
}

export async function buildAgentGuideModule() {
  const raw = await readFile(outlinePath, 'utf8')
  const outline = JSON.parse(raw)
  const outlineHash = createHash('sha256').update(raw).digest('hex')
  const text = renderGuide(outline)
  return { text, outlineHash, moduleSource: emitModule(text, outlineHash) }
}

async function main() {
  const check = process.argv.includes('--check')
  const write = process.argv.includes('--write')
  if (!check && !write) {
    console.error('Usage: node scripts/agent-guide-generate.mjs --write | --check')
    process.exit(1)
  }
  const { moduleSource, outlineHash } = await buildAgentGuideModule()
  if (write) {
    await writeFile(outputPath, moduleSource, 'utf8')
    console.log(`Wrote ${path.relative(root, outputPath)} (${outlineHash.slice(0, 12)}…)`)
    return
  }
  const existing = await readFile(outputPath, 'utf8')
  if (existing !== moduleSource) {
    console.error('Agent guide is out of date. Run: npm run guide:generate')
    process.exit(1)
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
